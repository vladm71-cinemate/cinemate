package com.cinemate.app.domain.model

/**
 * Вид отображения каталога:
 * GRID  — сетка, 3 постера в строке (старое имя сохранено, чтобы ранее
 *         сохранённые настройки продолжали работать),
 * GRID2 — сетка, 2 постера в строке (крупнее),
 * LIST  — компактные строки: постер слева, название и год справа.
 */
enum class HomeViewMode {
    GRID,   // 3 в строке
    GRID2,  // 2 в строке
    LIST
}